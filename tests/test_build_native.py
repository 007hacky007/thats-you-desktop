class BuildTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.out = Path(self.tmp.name) / "native"
        self.now = dt.datetime(2026, 11, 26, 12, 0, 0, tzinfo=dt.timezone.utc)

    def tearDown(self):
        self.tmp.cleanup()

    def test_macos_command_env_and_outputs(self):
        run = FakeRun()
        r = bn.build("macos-arm64", self.out, run=run, env={"PATH": "/bin"}, which=which_none,
                     now=self.now, host="macos-arm64")
        self.assertEqual(r["status"], "built")
        (call,) = run.builds()
        lib = self.out / "macos-arm64" / "iwyknet.dylib"
        self.assertEqual(call.cmd, ["go", "build", "-trimpath", "-buildmode=c-shared", "-ldflags", "-s -w",
                                    "-o", str(lib), "./capi"])
        self.assertEqual(Path(call.cwd), bn.NATIVE_DIR)
        self.assertEqual({k: call.env[k] for k in ("CGO_ENABLED", "GOOS", "GOARCH")},
                         {"CGO_ENABLED": "1", "GOOS": "darwin", "GOARCH": "arm64"})
        self.assertNotIn("CC", call.env)
        self.assertEqual(call.env["PATH"], "/bin")
        # The cgo header is replaced by the committed one.
        self.assertEqual((self.out / "macos-arm64" / "iwyknet.h").read_bytes(), bn.HEADER.read_bytes())
        info = json.loads((self.out / "macos-arm64" / "build-info.json").read_text())
        self.assertEqual(info["platform"], "macos-arm64")
        self.assertEqual(info["go_version"], "go1.27.4")
        self.assertEqual(info["commit"], "0123abc")
        self.assertEqual(info["built_utc"], "2026-11-26T12:00:00Z")
        self.assertEqual(info["sha256"], bn._sha256(lib))
        self.assertNotIn("dll_imports", info)

    def test_windows_cross_build_uses_mingw_and_checks_imports(self):
        run = FakeRun(objdump_text=GOOD_OBJDUMP)
        r = bn.build("win-x64", self.out, run=run, env={},
                     which=which_only(bn.MINGW_CC, bn.MINGW_OBJDUMP), now=self.now, host="macos-arm64")
        self.assertEqual(r["status"], "built")
        (call,) = run.builds()
        self.assertTrue(call.cmd[call.cmd.index("-o") + 1].endswith("win-x64/iwyknet.dll"))
        self.assertEqual({k: call.env[k] for k in ("CGO_ENABLED", "GOOS", "GOARCH", "CC")},
                         {"CGO_ENABLED": "1", "GOOS": "windows", "GOARCH": "amd64", "CC": bn.MINGW_CC})
        info = json.loads((self.out / "win-x64" / "build-info.json").read_text())
        self.assertEqual(info["dll_imports"], ["KERNEL32.dll", "api-ms-win-crt-heap-l1-1-0.dll"])
        self.assertEqual(info["cc"], bn.MINGW_CC)

    def test_windows_zig_and_env_override(self):
        run = FakeRun()
        bn.build("win-x64", self.out, run=run, env={}, which=which_only("zig"), host="macos-arm64")
        self.assertEqual(run.builds()[0].env["CC"], "zig cc -target x86_64-windows-gnu")
        run = FakeRun()
        bn.build("win-x64", self.out, run=run, env={"IWYK_WIN_CC": "my-cc"}, which=which_none, host="macos-arm64")
        self.assertEqual(run.builds()[0].env["CC"], "my-cc")

    def test_windows_bad_import_fails(self):
        run = FakeRun(objdump_text=BAD_OBJDUMP)
        with self.assertRaisesRegex(bn.BuildError, "libwinpthread"):
            bn.build("win-x64", self.out, run=run, env={}, which=which_only(bn.MINGW_CC, bn.MINGW_OBJDUMP),
                     host="macos-arm64")

    def test_windows_without_compiler_is_skipped_with_hint(self):
        run = FakeRun()
        r = bn.build("win-x64", self.out, run=run, env={}, which=which_none, host="macos-arm64")
        self.assertEqual(r["status"], "skipped")
        self.assertIn("go build -trimpath -buildmode=c-shared", r["message"])
        self.assertIn("IWYK_WIN_CC", r["message"])
        self.assertEqual(run.builds(), [])

    def test_native_windows_build_needs_no_cc(self):
        run = FakeRun()
        bn.build("win-x64", self.out, run=run, env={}, which=which_none, host="win-x64")
        self.assertNotIn("CC", run.builds()[0].env)

    def test_failures(self):
        with self.assertRaisesRegex(bn.BuildError, "boom"):
            bn.build("macos-arm64", self.out, run=FakeRun(fail_build=True), env={}, which=which_none,
                     host="macos-arm64")
        with self.assertRaises(bn.BuildError):
            bn.build("linux-x64", self.out, run=FakeRun(), env={})
        r = bn.build("macos-arm64", self.out, run=FakeRun(), env={}, host="win-x64")
        self.assertEqual(r["status"], "skipped")

    def test_build_is_repeatable(self):
        for _ in range(2):
            r = bn.build("macos-arm64", self.out, run=FakeRun(), env={}, which=which_none, host="macos-arm64")
            self.assertEqual(r["status"], "built")
        self.assertEqual(sorted(p.name for p in (self.out / "macos-arm64").iterdir()),
                         ["build-info.json", "iwyknet.dylib", "iwyknet.h"])

    def test_bot_build(self):
        run = FakeRun()
        bot = bn.build_bot(self.out, run=run, env={"GOOS": "windows", "CC": "x"})
        (call,) = run.builds()
        self.assertEqual(call.cmd[-1], "./cmd/iwykbot")
        self.assertEqual(call.env["CGO_ENABLED"], "0")
        self.assertNotIn("GOOS", call.env)
        self.assertNotIn("CC", call.env)
        self.assertEqual(bot.parent, self.out / bn.host_platform())

    def test_cli_skips_windows_and_returns_zero(self):
        calls = []

        def fake_build(plat, out):
            calls.append(plat)
            return {"platform": plat, "status": "skipped", "message": "x"}

        orig = bn.build
        bn.build = fake_build
        try:
            with contextlib.redirect_stdout(io.StringIO()) as so:
                self.assertEqual(bn.main(["--out", str(self.out)]), 0)
            self.assertIn("win-x64: skipped", so.getvalue())
            self.assertEqual(calls, ["macos-arm64", "win-x64"])
            calls.clear()
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(bn.main(["--platform", "win-x64", "--out", str(self.out)]), 0)
            self.assertEqual(calls, ["win-x64"])
        finally:
            bn.build = orig


class InstallTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.native = root / "native"
        self.project = root / "project"
        (self.project / "Assets").mkdir(parents=True)
        for plat in bn.PLATFORMS:
            d = self.native / plat
            d.mkdir(parents=True)
            (d / bn.LIB_NAME[plat]).write_bytes(b"lib-" + plat.encode())
        self.free = lambda p: []

    def tearDown(self):
        self.tmp.cleanup()

    def test_layout(self):
        rep = bn.install(self.native, self.project, holders=self.free)
        mac = self.project / "Assets/PortNative/iwyknet/macOS/iwyknet.dylib"
        win = self.project / "Assets/PortNative/iwyknet/Windows/x86_64/iwyknet.dll"
        self.assertEqual(mac.read_bytes(), b"lib-macos-arm64")
        self.assertEqual(win.read_bytes(), b"lib-win-x64")
        self.assertEqual(Path(str(mac) + ".meta").read_text(), (bn.META_DIR / "iwyknet.dylib.meta").read_text())
        self.assertEqual(Path(str(win) + ".meta").read_text(), (bn.META_DIR / "iwyknet.dll.meta").read_text())
        self.assertEqual(len(rep["copied"]), 2)
        self.assertEqual(len(rep["meta_written"]), 2)
        self.assertFalse((self.project / "Assets/Port").exists())
        self.assertFalse((self.project / "Assets/Plugins").exists())

    def test_idempotent_and_keeps_normalised_meta(self):
        bn.install(self.native, self.project, holders=self.free)
        meta = self.project / "Assets/PortNative/iwyknet/macOS/iwyknet.dylib.meta"
        meta.write_text(meta.read_text() + "  # normalised by Unity\n")
        rep = bn.install(self.native, self.project, holders=self.free)
        self.assertEqual(rep["copied"], [])
        self.assertEqual(len(rep["unchanged"]), 2)
        self.assertEqual(rep["meta_written"], [])
        self.assertIn("normalised", meta.read_text())
        (self.native / "macos-arm64/iwyknet.dylib").write_bytes(b"lib-new")
        rep = bn.install(self.native, self.project, holders=self.free)
        self.assertEqual(rep["copied"], ["Assets/PortNative/iwyknet/macOS/iwyknet.dylib"])

    def test_wrong_guid_meta_is_replaced(self):
        meta = self.project / "Assets/PortNative/iwyknet/Windows/x86_64/iwyknet.dll.meta"
        meta.parent.mkdir(parents=True)
        meta.write_text("fileFormatVersion: 2\nguid: " + "0" * 32 + "\n")
        rep = bn.install(self.native, self.project, holders=self.free)
        self.assertIn("Assets/PortNative/iwyknet/Windows/x86_64/iwyknet.dll.meta", rep["meta_written"])

    def test_refuses_when_unity_holds_project(self):
        with self.assertRaisesRegex(bn.BuildError, "Unity holds"):
            bn.install(self.native, self.project, holders=lambda p: [4242])
        self.assertFalse((self.project / "Assets/PortNative").exists())

    def test_default_lock_check_uses_build_player(self):
        from pipeline import build_player
        seen = []
        orig = build_player.lock_holders
        build_player.lock_holders = lambda p: seen.append(p) or [7]
        try:
            with self.assertRaises(bn.BuildError):
                bn.install(self.native, self.project)
        finally:
            build_player.lock_holders = orig
        self.assertEqual(seen, [self.project])

    def test_missing_binaries(self):
        shutil.rmtree(self.native / "win-x64")
        rep = bn.install(self.native, self.project, holders=self.free)
        self.assertEqual(rep["missing"], ["win-x64"])
        shutil.rmtree(self.native / "macos-arm64")
        with self.assertRaisesRegex(bn.BuildError, "no built binaries"):
            bn.install(self.native, self.project, holders=self.free)

    def test_not_a_project(self):
        with self.assertRaises(bn.BuildError):
            bn.install(self.native, Path(self.tmp.name) / "nothing", holders=self.free)

    def test_meta_templates(self):
        guids = set()
        for name in ("iwyknet.dylib.meta", "iwyknet.dll.meta"):
            text = (bn.META_DIR / name).read_text()
            self.assertTrue(text.isascii())
            g = bn._meta_guid(text)
            self.assertRegex(g or "", r"^[0-9a-f]{32}$")
            guids.add(g)
            self.assertIn("PluginImporter:", text)
        self.assertEqual(len(guids), 2)
        mac = (bn.META_DIR / "iwyknet.dylib.meta").read_text()
        self.assertRegex(mac, r"Editor:\n      enabled: 1\n      settings:\n        CPU: ARM64\n"
                              r"        DefaultValueInitialized: true\n        OS: OSX")
        self.assertRegex(mac, r"OSXUniversal:\n      enabled: 1\n      settings:\n        CPU: ARM64")
        self.assertRegex(mac, r"Win64:\n      enabled: 0")
        win = (bn.META_DIR / "iwyknet.dll.meta").read_text()
        self.assertRegex(win, r"Win64:\n      enabled: 1\n      settings:\n        CPU: x86_64")
        self.assertRegex(win, r"Editor:\n      enabled: 0")
        self.assertRegex(win, r"OSXUniversal:\n      enabled: 0")


class IwykEvent(ctypes.Structure):
    _fields_ = [(n, ctypes.c_int32) for n in ("kind", "session", "transfer_id", "code", "len")]


@unittest.skipUnless(HAVE_GO and IS_MAC_ARM, "needs go on an Apple Silicon Mac")
class RealMacBuildTests(unittest.TestCase):
    def test_build_and_drive_with_ctypes(self):
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / "native"
            r = bn.build("macos-arm64", out)
            self.assertEqual(r["status"], "built")
            lib = ctypes.CDLL(r["path"])
            for name in ("iwyk_start",):
                getattr(lib, name).argtypes = [ctypes.c_int32, ctypes.c_char_p, ctypes.c_char_p]
            lib.iwyk_join_url.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_int32]
            lib.iwyk_endpoint.argtypes = [ctypes.c_char_p, ctypes.c_int32]
            lib.iwyk_qr.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_int32, ctypes.POINTER(ctypes.c_int32)]
            lib.iwyk_poll.argtypes = [ctypes.POINTER(IwykEvent), ctypes.c_char_p, ctypes.c_int32]
            self.assertEqual(lib.iwyk_abi_version(), 1)
            self.assertEqual(ctypes.sizeof(IwykEvent), 20)
            cert = str(Path(d) / "cert" / "dtls.pem").encode()
            self.assertEqual(lib.iwyk_set_log_level(4), 0)
            self.assertEqual(lib.iwyk_start(0, b"127.0.0.1", cert), 0)
            try:
                buf = ctypes.create_string_buffer(4096)
                n = lib.iwyk_endpoint(buf, 4096)
                self.assertGreater(n, 0)
                self.assertRegex(buf.raw[:n].decode(), r"^127\.0\.0\.1:\d+$")
                n = lib.iwyk_join_url(b"https://example.invalid/iwyk/#x", buf, 4096)
                self.assertGreater(n, 0)
                join = buf.raw[:n].decode()
                m = JOIN_RE.match(join)
                self.assertIsNotNone(m, join)
                self.assertEqual(m.group(1), "127.0.0.1")
                mods = ctypes.create_string_buffer(31329)
                side = ctypes.c_int32(0)
                self.assertEqual(lib.iwyk_qr(join.encode(), mods, 31329, ctypes.byref(side)), 0)
                self.assertGreaterEqual(side.value, 21)
                self.assertTrue(set(mods.raw[:side.value ** 2]) <= {0, 1})
                ev = IwykEvent()
                self.assertEqual(lib.iwyk_poll(ctypes.byref(ev), buf, 4096), 0)
            finally:
                self.assertEqual(lib.iwyk_stop(), 0)
            self.assertEqual(lib.iwyk_stop(), 0)
            self.assertEqual(oct((Path(d) / "cert" / "dtls.pem").stat().st_mode & 0o777), "0o600")


@unittest.skipUnless(HAVE_GO and HAVE_MINGW, "needs go and mingw-w64")
class RealWindowsCrossBuildTests(unittest.TestCase):
    def test_cross_build_dll(self):
        with tempfile.TemporaryDirectory() as d:
            r = bn.build("win-x64", Path(d), host="macos-arm64")
            self.assertEqual(r["status"], "built")
            imports = r["info"]["dll_imports"]
            self.assertIn("KERNEL32.dll", imports)
            for name in imports:
                self.assertRegex(name, bn.ALLOWED_DLL_IMPORT)
            text = subprocess.run([shutil.which(bn.MINGW_OBJDUMP), "-p", r["path"]], capture_output=True,
                                  text=True).stdout
            for fn in ("iwyk_start", "iwyk_poll", "iwyk_send_binary", "iwyk_last_error"):
                self.assertIn(fn, text)


