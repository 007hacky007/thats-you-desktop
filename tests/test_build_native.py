class FakeRun:
    """Records commands; go build creates the output file and a cgo header like the real one."""

    def __init__(self, objdump_text="", fail_build=False):
        self.calls = []
        self.objdump_text = objdump_text
        self.fail_build = fail_build

    def __call__(self, cmd, cwd=None, env=None, capture_output=False, text=False, **kw):
        self.calls.append(SimpleNamespace(cmd=list(cmd), cwd=cwd, env=env))
        if cmd[:2] == ["go", "build"]:
            if self.fail_build:
                return SimpleNamespace(returncode=1, stdout="", stderr="boom")
            out = Path(cmd[cmd.index("-o") + 1])
            out.write_bytes(b"binary:" + out.name.encode())
            if "-buildmode=c-shared" in cmd:
                out.with_name("iwyknet.h").write_text("/* generated by cgo */")
            return SimpleNamespace(returncode=0, stdout="", stderr="")
        if cmd[:3] == ["go", "env", "GOVERSION"]:
            return SimpleNamespace(returncode=0, stdout="go1.27.4\n", stderr="")
        if cmd[0] == "git":
            return SimpleNamespace(returncode=0, stdout="0123abc\n", stderr="")
        if cmd[-2:-1] == ["-p"]:
            return SimpleNamespace(returncode=0, stdout=self.objdump_text, stderr="")
        return SimpleNamespace(returncode=1, stdout="", stderr="unexpected")

    def builds(self):
        return [c for c in self.calls if c.cmd[:2] == ["go", "build"]]


def which_none(_name):
    return None


def which_only(*names):
    return lambda n: f"/usr/bin/{n}" if n in names else None


GOOD_OBJDUMP = "\tDLL Name: KERNEL32.dll\n\tDLL Name: api-ms-win-crt-heap-l1-1-0.dll\n"
BAD_OBJDUMP = GOOD_OBJDUMP + "\tDLL Name: libwinpthread-1.dll\n"


class ConfigTests(unittest.TestCase):
    def test_work_dir_from_config(self):
        with tempfile.TemporaryDirectory() as d:
            cfg = Path(d) / "local.json"
            cfg.write_text(json.dumps({"work_dir": d + "/w", "base_dump": "/nope"}))
            self.assertEqual(bn.work_dir(cfg), Path(d) / "w")
            cfg.write_text(json.dumps({"work_dir": ""}))
            self.assertEqual(bn.work_dir(cfg), bn.REPO_ROOT / "work")
            cfg.write_text("{broken")
            self.assertEqual(bn.work_dir(cfg), bn.REPO_ROOT / "work")
            self.assertEqual(bn.work_dir(Path(d) / "missing.json"), bn.REPO_ROOT / "work")

    def test_host_platform(self):
        self.assertEqual(bn.host_platform("Darwin", "arm64"), "macos-arm64")
        self.assertEqual(bn.host_platform("Windows", "AMD64"), "win-x64")
        self.assertEqual(bn.host_platform("Linux", "x86_64"), "linux-x86_64")


